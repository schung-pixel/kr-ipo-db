class FinancialsTest(unittest.TestCase):
    def test_consolidated_with_separate_income_header(self):
        r = financials.extract_financials(CONSOL)
        self.assertEqual(r["basis"], "연결")
        self.assertEqual(r["periods"], ["2019 3분기", "2018", "2017"])
        self.assertEqual(r["revenue"][0], 23944642022)
        self.assertEqual(r["net_income"][1], 2542974201)
        self.assertEqual(r["equity"][2], 10155029211)    # 별도(다.)가 아니라 연결 값
        self.assertTrue(r["check"])
        self.assertEqual(r["unit"], "원")                 # EPS 행의 '(단위 : 원)'에 끌려가지 않음

    def test_merged_cells_thousand_won(self):
        r = financials.extract_financials(MERGED)
        self.assertEqual(r["periods"], ["2022 1분기", "2021", "2020"])
        self.assertEqual(r["revenue"], [51549583000, 147254000000, 65900000000])
        self.assertEqual(r["op_income"][2], -6300000000)
        self.assertEqual(r["net_income"][1], -12000000000)
        self.assertEqual(r["assets"][0], 227646689000)

    def test_income_table_with_comparative_column(self):
        r = financials.extract_financials(WIDER)
        self.assertEqual(r["periods"], ["2024 1분기", "2023", "2023 1분기"])
        self.assertEqual(r["revenue"], [7442_000000, 30049_000000, 7363_000000])
        self.assertEqual(r["assets"], [34798_000000, 33970_000000, None])

    def test_export_view(self):
        v = _fin_view(dict(financials.extract_financials(CONSOL), src="20191101000001"))
        self.assertEqual(v["periods"], ["2019 3분기", "2018", "2017"])
        self.assertEqual(v["revenue"][0], 23945)          # 백만원
        self.assertEqual(v["src"], "20191101000001")
        self.assertIsNone(_fin_view({"periods": ["2019"], "check": False}))


